import {readFile,writeFile} from 'node:fs/promises';

// Keep the standalone browser build free of a JSON-import compatibility requirement.
const input=new URL('../data/sternicza-appearance-observations.json',import.meta.url);
const output=new URL('../src/neighborhood-appearance-data.js',import.meta.url);
const data=JSON.parse(await readFile(input,'utf8'));
const code=`// Generated by scripts/generate-neighborhood-appearance.mjs. Edit the source JSON.\n`
  +`const freeze=value=>{if(value&&typeof value==='object'){Object.values(value).forEach(freeze);Object.freeze(value);}return value;};\n`
  +`export const neighborhoodAppearanceData=freeze(${JSON.stringify(data,null,2)});\n`;
await writeFile(output,code);
